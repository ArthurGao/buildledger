import type { System } from "./types";

/**
 * Page notes shown to the client during a walkthrough.
 *
 * These explain, per page, what goes in, what comes out, where AI and
 * automation act, and which manual processes the platform replaces. They are
 * written in Chinese for the audience this demo is presented to; the product
 * interface itself stays in English.
 *
 * All of it lives in this file plus one component, so it can be removed by
 * dropping <PageGuideButton /> from the header.
 */

export interface PageGuide {
  /** Page name shown as the panel title. */
  title: string;
  /** The page name as it appears in the interface. */
  englishTitle: string;
  /** One sentence: what this page is for. */
  purpose: string;
  /** What flows into this page, and from which system. */
  inputs: { system: System; what: string }[];
  /** What the page produces. */
  outputs: string[];
  /** How to actually work with the page. */
  howToUse: string[];
  /** Where AI and automation do the work a person used to do. */
  automation: { step: string; detail: string }[];
  /** The manual process this replaces, paired with what happens now. */
  before: { before: string; after: string }[];
  /** Questions the client is likely to ask, with answers. */
  faq: { q: string; a: string }[];
}

